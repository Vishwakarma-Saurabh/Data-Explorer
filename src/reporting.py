from __future__ import annotations

import pandas as pd


def build_profile_table(df: pd.DataFrame, labels: "pd.Series | list", numeric_cols: list[str]) -> dict:

    profile_df = df[numeric_cols].copy()
    profile_df["__cluster__"] = list(labels)

    cluster_means = profile_df.groupby("__cluster__")[numeric_cols].mean()
    cluster_sizes = profile_df.groupby("__cluster__").size().rename("size")
    overall_mean = df[numeric_cols].mean()
    overall_std = df[numeric_cols].std(ddof=0).replace(0, 1.0)

    z_scores = (cluster_means - overall_mean) / overall_std

    return {
        "cluster_means": cluster_means,
        "overall_mean": overall_mean,
        "overall_std": overall_std,
        "z_scores": z_scores,
        "cluster_sizes": cluster_sizes,
    }


def top_features_per_cluster(profile: dict, top_n: int = 3) -> dict[int, list[dict]]:

    z = profile["z_scores"]
    means = profile["cluster_means"]
    overall = profile["overall_mean"]

    out: dict[int, list[dict]] = {}
    for cluster_id in z.index:
        row = z.loc[cluster_id].sort_values(key=lambda s: s.abs(), ascending=False)
        top = row.head(top_n)
        features = []
        for feat, z_val in top.items():
            features.append({
                "feature": str(feat),
                "z": float(z_val),
                "cluster_mean": float(means.loc[cluster_id, feat]),
                "overall_mean": float(overall[feat]),
                "direction": "higher" if z_val > 0 else "lower",
            })
        out[int(cluster_id)] = features
    return out


def describe_cluster(cluster_id: int, features: list[dict], size: int) -> str:

    if not features:
        return f"Cluster {cluster_id} ({size} rows) has no distinguishing features."

    parts = []
    for f in features[:2]:
        parts.append(f"{f['direction']} {f['feature']} (z={f['z']:+.2f})")

    return f"Cluster {cluster_id} ({size} rows) is characterized by " + ", ".join(parts) + "."


def build_markdown_report(
    filename: str,
    profile: dict,
    top_features: dict[int, list[dict]],
    descriptions: dict[int, str],
    silhouette_scores: list[dict],
    best_k: int,
    explained_variance: list[float],
) -> str:

    lines = []
    lines.append(f"# Auto EDA Report — {filename}")
    lines.append("")
    lines.append("## Clustering summary")
    lines.append(f"- Auto-selected K: **{best_k}**")
    if silhouette_scores:
        best = max(silhouette_scores, key=lambda r: r["silhouette"])
        lines.append(f"- Best silhouette: **{best['silhouette']:.3f}** (K={best['k']})")
    if explained_variance:
        ev_2d = sum(explained_variance[:2])
        lines.append(f"- PC1 + PC2 explain: **{ev_2d:.1%}** of variance")
    lines.append("")

    lines.append("## Cluster sizes")
    sizes = profile["cluster_sizes"]
    total = int(sizes.sum())
    for cid, size in sizes.items():
        pct = size / total * 100 if total else 0
        lines.append(f"- Cluster {cid}: {int(size)} rows ({pct:.1f}%)")
    lines.append("")

    lines.append("## Cluster descriptions")
    for cid, desc in descriptions.items():
        lines.append(f"### {desc}")
        lines.append("")
        feats = top_features.get(cid, [])
        if feats:
            lines.append("| Feature | Cluster mean | Overall mean | z-score |")
            lines.append("|---|---|---|---|")
            for f in feats:
                lines.append(
                    f"| {f['feature']} | {f['cluster_mean']:.3g} | "
                    f"{f['overall_mean']:.3g} | {f['z']:+.2f} |"
                )
            lines.append("")

    lines.append("---")
    lines.append("*Generated by Auto EDA Studio. Z-scores are standardized "
                 "differences between cluster mean and overall mean; "
                 "|z| > 1 indicates a cluster meaningfully above or below the population.*")
    return "\n".join(lines)